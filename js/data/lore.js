export function isLoreUnlocked(loreId) {
  if (typeof window === 'undefined') return false;
  const unlocked = window.GameState?.UNLOCKED_LORE || {};
  if (unlocked[loreId]) return true;

  // Check legacy alias mappings
  const item = LORE_SCROLLS_DATA.find(l => l.id === loreId);
  if (item && item.legacyId && unlocked[item.legacyId]) return true;

  // Check if primary entry unlocked by legacy ID
  const primary = LORE_SCROLLS_DATA.find(l => l.legacyId === loreId);
  if (primary && unlocked[primary.id]) return true;

  return false;
}
